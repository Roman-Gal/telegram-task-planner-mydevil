CREATE TABLE IF NOT EXISTS users (
 id BIGINT PRIMARY KEY, username TEXT, name TEXT NOT NULL, private_enabled INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS members (
 chat_id BIGINT NOT NULL, user_id BIGINT NOT NULL REFERENCES users(id), PRIMARY KEY(chat_id,user_id)
);
CREATE TABLE IF NOT EXISTS tasks (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, source_update_id BIGINT UNIQUE NOT NULL,
 chat_id BIGINT NOT NULL, thread_id BIGINT, creator_id BIGINT NOT NULL REFERENCES users(id),
 assignee_id BIGINT NOT NULL REFERENCES users(id), description TEXT NOT NULL,
 due_at BIGINT NOT NULL, status TEXT NOT NULL DEFAULT 'open', generation INTEGER NOT NULL DEFAULT 0,
 created_at BIGINT NOT NULL, updated_at BIGINT NOT NULL, priority TEXT NOT NULL DEFAULT 'medium',
 reminder_minutes TEXT NOT NULL DEFAULT '[]', next_overdue_at BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS tasks_due ON tasks(status,due_at);
CREATE INDEX IF NOT EXISTS tasks_chat ON tasks(chat_id,status);
CREATE TABLE IF NOT EXISTS deliveries (
 task_id BIGINT NOT NULL REFERENCES tasks(id), generation INTEGER NOT NULL,
 event_at BIGINT NOT NULL, kind TEXT NOT NULL, destination TEXT NOT NULL, chat_id BIGINT NOT NULL,
 thread_id BIGINT, state TEXT NOT NULL DEFAULT 'pending', attempts INTEGER NOT NULL DEFAULT 0,
 next_attempt_at BIGINT NOT NULL, last_code INTEGER, PRIMARY KEY(task_id,generation,event_at,destination)
);
CREATE INDEX IF NOT EXISTS deliveries_pending ON deliveries(state,next_attempt_at);
CREATE TABLE IF NOT EXISTS updates (
 id BIGINT PRIMARY KEY, payload TEXT NOT NULL, state TEXT NOT NULL DEFAULT 'pending',
 attempts INTEGER NOT NULL DEFAULT 0, next_attempt_at BIGINT NOT NULL DEFAULT 0, received_at BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS actions (update_id BIGINT PRIMARY KEY, result TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS drafts (
 id TEXT PRIMARY KEY, start_update_id BIGINT UNIQUE NOT NULL, chat_id BIGINT NOT NULL,
 user_id BIGINT NOT NULL, thread_id BIGINT NOT NULL, revision INTEGER NOT NULL, body TEXT NOT NULL, expires_at BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS wizard_receipts (update_id BIGINT PRIMARY KEY, body TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS group_access (chat_id BIGINT PRIMARY KEY, owner_id BIGINT NOT NULL, approved_at BIGINT NOT NULL);
CREATE TABLE IF NOT EXISTS user_picks (
 request_id INTEGER PRIMARY KEY, draft_id TEXT NOT NULL, user_id BIGINT NOT NULL, expires_at BIGINT NOT NULL, consumed INTEGER NOT NULL DEFAULT 0
);
